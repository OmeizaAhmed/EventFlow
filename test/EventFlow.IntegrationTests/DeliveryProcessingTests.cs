    public DeliveryProcessingTests()
    {
        _postgresAdminConnectionString = Environment.GetEnvironmentVariable("EVENTFLOW_DELIVERY_TEST_POSTGRES");
        if (!string.IsNullOrWhiteSpace(_postgresAdminConnectionString))
        {
            _postgresDatabaseName = $"eventflow_delivery_test_{Guid.NewGuid():N}";
            _postgresTestConnectionString = new NpgsqlConnectionStringBuilder(_postgresAdminConnectionString)
            {
                Database = _postgresDatabaseName
            }.ConnectionString;
        }
        _webhookClient = new HttpClient(_handler) { Timeout = Timeout.InfiniteTimeSpan };
        _factory = _baseFactory.WithWebHostBuilder(builder => builder.ConfigureTestServices(services =>
        {
            if (_postgresTestConnectionString is not null)
            {
                services.RemoveAll<DbContextOptions<EventFlowDbContext>>();
                services.RemoveAll<IDbContextOptionsConfiguration<EventFlowDbContext>>();
                services.AddDbContext<EventFlowDbContext>(options => options.UseNpgsql(_postgresTestConnectionString));
            }
            services.RemoveAll<TimeProvider>();
            services.AddSingleton<TimeProvider>(_time);
            services.AddSingleton(provider => new DeliveryJobScheduler(() => _jobs,
                provider.GetRequiredService<ILogger<DeliveryJobScheduler>>()));
            services.Configure<DeliveryProcessingOptions>(options => options.MaxAttempts = 3);
            services.RemoveAll<IWebhookSender>();
            services.AddScoped<IWebhookSender>(provider => new WebhookSender(
                _webhookClient,
                provider.GetRequiredService<IWebhookSignatureGenerator>(),
                provider.GetRequiredService<IOptions<WebhookSenderOptions>>(),
                _time,
                provider.GetRequiredService<ILogger<WebhookSender>>()));
        }));
    }

    public async Task InitializeAsync()
    {
        if (_postgresDatabaseName is not null)
        {
            await using var connection = new NpgsqlConnection(_postgresAdminConnectionString);
            await connection.OpenAsync();
            // The identifier is generated here from a fixed prefix and a GUID, never supplied by the environment.
            await using var command = new NpgsqlCommand($"CREATE DATABASE \"{_postgresDatabaseName}\"", connection);
            await command.ExecuteNonQueryAsync();
            _postgresDatabaseCreated = true;
        }
        await using var scope = _factory.Services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<EventFlowDbContext>();
        if (_postgresTestConnectionString is not null)
            await db.Database.MigrateAsync();
        else
            await db.Database.EnsureCreatedAsync();
    }

    public async Task DisposeAsync()
    {
        try
        {
            await _factory.DisposeAsync();
            await _baseFactory.DisposeAsync();
            _webhookClient.Dispose();
        }
        finally
        {
            if (_postgresDatabaseCreated)
            {
                if (_postgresDatabaseName is null ||
                    !_postgresDatabaseName.StartsWith("eventflow_delivery_test_", StringComparison.Ordinal) ||
                    !Guid.TryParseExact(_postgresDatabaseName["eventflow_delivery_test_".Length..], "N", out _))
                    throw new InvalidOperationException("Refusing to remove a database not generated by this fixture.");

                using var testConnection = new NpgsqlConnection(_postgresTestConnectionString);
                NpgsqlConnection.ClearPool(testConnection);
                await using var admin = new NpgsqlConnection(_postgresAdminConnectionString);
                await admin.OpenAsync();
                await using var command = new NpgsqlCommand(
                    $"DROP DATABASE \"{_postgresDatabaseName}\" WITH (FORCE)", admin);
                await command.ExecuteNonQueryAsync();
                _postgresDatabaseCreated = false;
            }
        }
    }

    [Fact]
    public async Task PublishedEvent_ProcessesSignedWebhookAndPersistsCompletedAttempt()
    {
        var seeded = await SeedAsync(publish: false);
        _handler.Enqueue(HttpStatusCode.Accepted, "accepted");
        using var client = _factory.CreateClient(new WebApplicationFactoryClientOptions
        {
            BaseAddress = new Uri("https://localhost"),
            AllowAutoRedirect = false
        });
        client.DefaultRequestHeaders.Authorization = new AuthenticationHeaderValue("Bearer", seeded.ApiKey);
        client.DefaultRequestHeaders.Add("Idempotency-Key", "published-order");

        using var response = await client.PostAsJsonAsync($"/api/projects/{seeded.ProjectId}/events",
            new { EventType = "order.created", Payload = new { orderId = "order-42", total = 42 } });

        Assert.Equal(HttpStatusCode.Accepted, response.StatusCode);
        var queued = await ReadDeliveryAsync();
        Assert.Equal(DeliveryStatus.Queued, queued.Status);
        Assert.Empty(queued.Attempts);
        Assert.Empty(_handler.Requests);

        var publishJob = Assert.Single(_jobs.Created);
        Assert.Equal(nameof(DeliveryJobs.SendAsync), publishJob.Job.Method.Name);
        Assert.Equal(queued.DeliveryId, Assert.IsType<Guid>(publishJob.Job.Args[0]));
        Assert.IsType<EnqueuedState>(publishJob.State);
        await SendJobAsync(queued.DeliveryId);

        var completed = await ReadDeliveryAsync();
        Assert.Equal(DeliveryStatus.Delivered, completed.Status);
        Assert.Null(completed.NextRetryAt);
        Assert.Null(completed.LeaseToken);
        Assert.Null(completed.LeaseExpiresAt);
        var attempt = Assert.Single(completed.Attempts);
        Assert.NotEqual(Guid.Empty, attempt.DeliveryAttemptId);
        Assert.Equal(completed.DeliveryId, attempt.DeliveryId);
        Assert.Equal(1, attempt.AttemptNumber);
        Assert.True(attempt.Succeeded);
        Assert.Equal(202, attempt.HttpStatusCode);
        Assert.Null(attempt.ErrorMessage);
        Assert.Equal("accepted", attempt.ResponseBody);
        Assert.Equal(_time.GetUtcNow().UtcDateTime, attempt.AttemptedAt);
        Assert.True(attempt.DurationMilliseconds >= 0);

        var request = Assert.Single(_handler.Requests);
        Assert.Equal(HttpMethod.Post, request.Method);
        Assert.Equal("https://receiver.example/webhook", request.Url);
        Assert.Equal(completed.Event.Payload, request.Payload);
        Assert.Equal("application/json", request.ContentType);
        Assert.Equal(completed.EventId.ToString(), request.Headers["EventFlow-Event-Id"]);
        Assert.Equal(completed.DeliveryId.ToString(), request.Headers["EventFlow-Delivery-Id"]);
        Assert.Equal("order.created", request.Headers["EventFlow-Event-Type"]);
        var timestamp = _time.GetUtcNow().ToUnixTimeSeconds().ToString(CultureInfo.InvariantCulture);
        var signature = Convert.ToHexString(HMACSHA256.HashData(
            Encoding.UTF8.GetBytes(seeded.Secret), Encoding.UTF8.GetBytes($"{timestamp}.{request.Payload}")))
            .ToLowerInvariant();
        Assert.Equal(timestamp, request.Headers["EventFlow-Timestamp"]);
        Assert.Equal($"t={timestamp},v1={signature}", request.Headers["EventFlow-Signature"]);
        Assert.False(await ProcessNextAsync());
        Assert.Single(_handler.Requests);
    }

    [Fact]
    public async Task Claim_IsPersistedAndPreventsAnotherScopeFromOwningTheSameDelivery()
    {
        await SeedAsync();
        await using var firstScope = _factory.Services.CreateAsyncScope();
        await using var secondScope = _factory.Services.CreateAsyncScope();
        var now = _time.GetUtcNow().UtcDateTime;
        var leaseDuration = TimeSpan.FromMinutes(2);

        var firstRepository = firstScope.ServiceProvider.GetRequiredService<IDeliveryRepository>();
        var secondRepository = secondScope.ServiceProvider.GetRequiredService<IDeliveryRepository>();
        Delivery?[] claims;
        if (_postgresTestConnectionString is not null)
        {
            // PostgreSQL contexts have separate connections: release both workers together to race the claim.
            var start = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
            async Task<Delivery?> ClaimTogetherAsync(IDeliveryRepository repository)
            {
                await start.Task;
                return await repository.ClaimNextAsync(now, leaseDuration);
            }
            var firstTask = ClaimTogetherAsync(firstRepository);
            var secondTask = ClaimTogetherAsync(secondRepository);
            start.SetResult();
            claims = await Task.WhenAll(firstTask, secondTask);
        }
        else
        {
            // The default SQLite factory shares one connection, so exercise persisted exclusion sequentially.
            claims = new[]
            {
                await firstRepository.ClaimNextAsync(now, leaseDuration),
                await secondRepository.ClaimNextAsync(now, leaseDuration)
            };
        }

        var first = Assert.Single(claims.Where(claim => claim is not null))!;
        Assert.Single(claims.Where(claim => claim is null));
        Assert.NotNull(first.LeaseToken);
        Assert.NotEqual(Guid.Empty, first.LeaseToken.Value);
        Assert.NotNull(first.Event.Project);
        Assert.NotNull(first.Endpoint);
        var persisted = await ReadDeliveryAsync();
        Assert.Equal(DeliveryStatus.Processing, persisted.Status);
        Assert.Equal(first.LeaseToken, persisted.LeaseToken);
        Assert.Equal(now.Add(leaseDuration), persisted.LeaseExpiresAt);
        Assert.Empty(persisted.Attempts);
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task ExpiredLease_IsReclaimedAndStaleWorkerCannotPersistItsAttempt(bool replacementSavesFirst)
    {
        await SeedAsync();
        await using var firstScope = _factory.Services.CreateAsyncScope();
        await using var secondScope = _factory.Services.CreateAsyncScope();
        var firstRepository = firstScope.ServiceProvider.GetRequiredService<IDeliveryRepository>();
        var secondRepository = secondScope.ServiceProvider.GetRequiredService<IDeliveryRepository>();
        var leaseDuration = TimeSpan.FromMinutes(2);
        var first = await firstRepository.ClaimNextAsync(_time.GetUtcNow().UtcDateTime, leaseDuration);
        Assert.NotNull(first);
        var firstToken = first.LeaseToken!.Value;
        _time.Advance(leaseDuration + TimeSpan.FromSeconds(1));
        var recovered = await secondRepository.ClaimNextAsync(_time.GetUtcNow().UtcDateTime, leaseDuration);
        Assert.NotNull(recovered);
        Assert.Equal(first.DeliveryId, recovered.DeliveryId);
        var recoveredToken = recovered.LeaseToken!.Value;
        Assert.NotEqual(firstToken, recoveredToken);

        recovered.RecordAttempt(204, null, true, _time.GetUtcNow().UtcDateTime, string.Empty, 5);
        if (replacementSavesFirst)
            Assert.True(await secondRepository.SaveClaimedAsync(recovered, recoveredToken));

        first.RecordAttempt(200, null, true, _time.GetUtcNow().UtcDateTime, "stale response", 10);
        Assert.False(await firstRepository.SaveClaimedAsync(first, firstToken));
        if (!replacementSavesFirst)
        {
            var stillOwned = await ReadDeliveryAsync();
            Assert.Equal(DeliveryStatus.Processing, stillOwned.Status);
            Assert.Equal(recoveredToken, stillOwned.LeaseToken);
            Assert.Empty(stillOwned.Attempts);
            Assert.True(await secondRepository.SaveClaimedAsync(recovered, recoveredToken));
        }
        var completed = await ReadDeliveryAsync();
        Assert.Equal(DeliveryStatus.Delivered, completed.Status);
        Assert.Equal(204, Assert.Single(completed.Attempts).HttpStatusCode);
    }

    [Fact]
    public async Task RetryableFailure_WaitsUntilDueThenPreservesHistoryOnSuccess()
    {
        await SeedAsync();
        _time.Advance(TimeSpan.FromMilliseconds(237));
        _handler.Enqueue(HttpStatusCode.ServiceUnavailable, "try later", TimeSpan.FromMinutes(2));
        _handler.Enqueue(HttpStatusCode.OK, "received");

        var deliveryId = (await ReadDeliveryAsync()).DeliveryId;
        await SendJobAsync(deliveryId);
        var failed = await ReadDeliveryAsync();
        Assert.Equal(DeliveryStatus.RetryScheduled, failed.Status);
        Assert.NotNull(failed.NextRetryAt);
        Assert.True(failed.NextRetryAt > _time.GetUtcNow().UtcDateTime);
        Assert.False(Assert.Single(failed.Attempts).Succeeded);
        Assert.Equal(503, Assert.Single(failed.Attempts).HttpStatusCode);
        var retryJob = Assert.Single(_jobs.Created.Skip(1));
        Assert.Equal(deliveryId, Assert.IsType<Guid>(retryJob.Job.Args[0]));
        Assert.Equal(failed.NextRetryAt.Value.AddMilliseconds(763),
            Assert.IsType<ScheduledState>(retryJob.State).EnqueueAt);
        await SendJobAsync(deliveryId);
        _time.SetUtcNow(new DateTimeOffset(DateTime.SpecifyKind(failed.NextRetryAt.Value, DateTimeKind.Utc))
            .AddMilliseconds(-1));
        await SendJobAsync(deliveryId);
        Assert.Single(_handler.Requests);

        _time.Advance(TimeSpan.FromMilliseconds(1));
        await SendJobAsync(deliveryId);

        var completed = await ReadDeliveryAsync();
        Assert.Equal(DeliveryStatus.Delivered, completed.Status);
        Assert.Null(completed.NextRetryAt);
        Assert.Null(completed.LeaseToken);
        Assert.Collection(completed.Attempts.OrderBy(a => a.AttemptNumber),
            first =>
            {
                Assert.Equal(1, first.AttemptNumber);
                Assert.Equal(503, first.HttpStatusCode);
                Assert.False(first.Succeeded);
                Assert.Equal("try later", first.ResponseBody);
            },
            second =>
            {
                Assert.Equal(2, second.AttemptNumber);
                Assert.Equal(200, second.HttpStatusCode);
                Assert.True(second.Succeeded);
                Assert.Equal("received", second.ResponseBody);
            });
        Assert.Equal(2, _handler.Requests.Count);
        Assert.Equal(2, _jobs.Created.Count);
    }

    [Fact]
    public async Task Recovery_EnqueuesCommittedDeliveryAfterEnqueueFailureAndExpiredLease()
    {
        _jobs.FailEnqueue = true;
        await SeedAsync();
        var deliveryId = (await ReadDeliveryAsync()).DeliveryId;
        await using (var scope = _factory.Services.CreateAsyncScope())
        {
            var repository = scope.ServiceProvider.GetRequiredService<IDeliveryRepository>();
            Assert.NotNull(await repository.ClaimAsync(deliveryId, _time.GetUtcNow().UtcDateTime,
                TimeSpan.FromMinutes(1)));
        }

        _jobs.FailEnqueue = false;
        _time.Advance(TimeSpan.FromMinutes(1));
        await using (var scope = _factory.Services.CreateAsyncScope())
        {
            await scope.ServiceProvider.GetRequiredService<DeliveryJobs>().RecoverAsync(CancellationToken.None);
        }

        var recoveryJob = Assert.Single(_jobs.Created);
        Assert.Equal(deliveryId, Assert.IsType<Guid>(recoveryJob.Job.Args[0]));
        Assert.IsType<EnqueuedState>(recoveryJob.State);
        await SendJobAsync(deliveryId);
        await SendJobAsync(deliveryId);

        var completed = await ReadDeliveryAsync();
        Assert.Equal(DeliveryStatus.Delivered, completed.Status);
        Assert.Single(completed.Attempts);
        Assert.Single(_handler.Requests);
    }

    [Fact]
    public async Task PermanentFailure_DeadLettersDeliveryWithoutSchedulingAnotherAttempt()
    {
        await SeedAsync();
        _handler.Enqueue(HttpStatusCode.BadRequest, "invalid payload");

        Assert.True(await ProcessNextAsync());

        var delivery = await ReadDeliveryAsync();
        Assert.Equal(DeliveryStatus.DeadLetter, delivery.Status);
        Assert.Null(delivery.NextRetryAt);
        Assert.Null(delivery.LeaseToken);
        var attempt = Assert.Single(delivery.Attempts);
        Assert.False(attempt.Succeeded);
        Assert.Equal(400, attempt.HttpStatusCode);
        Assert.Equal("invalid payload", attempt.ResponseBody);
        Assert.NotNull(attempt.ErrorMessage);
        _time.Advance(TimeSpan.FromDays(1));
        Assert.False(await ProcessNextAsync());
        Assert.Single(_handler.Requests);
    }

    [Fact]
    public async Task RepeatedTransientFailure_StopsAtConfiguredAttemptLimit()
    {
        await SeedAsync();
        for (var attemptNumber = 1; attemptNumber <= 3; attemptNumber++)
        {
            _handler.Enqueue(HttpStatusCode.ServiceUnavailable, $"failure {attemptNumber}");
            Assert.True(await ProcessNextAsync());
            var delivery = await ReadDeliveryAsync();
            Assert.Equal(attemptNumber, delivery.Attempts.Count);
            Assert.All(delivery.Attempts, attempt => Assert.False(attempt.Succeeded));
            if (attemptNumber < 3)
            {
                Assert.Equal(DeliveryStatus.RetryScheduled, delivery.Status);
                Assert.NotNull(delivery.NextRetryAt);
                _time.SetUtcNow(new DateTimeOffset(DateTime.SpecifyKind(delivery.NextRetryAt.Value, DateTimeKind.Utc)));
            }
            else
            {
                Assert.Equal(DeliveryStatus.DeadLetter, delivery.Status);
                Assert.Null(delivery.NextRetryAt);
                Assert.Null(delivery.LeaseToken);
                Assert.Equal(new[] { 1, 2, 3 }, delivery.Attempts.Select(a => a.AttemptNumber).Order());
            }
        }
        _time.Advance(TimeSpan.FromDays(1));
        Assert.False(await ProcessNextAsync());
        Assert.Equal(3, _handler.Requests.Count);
    }

    [Theory]
    [InlineData("project")]
    [InlineData("endpoint")]
    public async Task DisabledDestination_IsNotClaimedUntilReactivated(string disabledResource)
    {
        var seeded = await SeedAsync();
        await using (var scope = _factory.Services.CreateAsyncScope())
        {
            var db = scope.ServiceProvider.GetRequiredService<EventFlowDbContext>();
            if (disabledResource == "project")
                (await db.Projects.SingleAsync(p => p.ProjectId == seeded.ProjectId)).Deactivate();
            else
                (await db.WebhookEndpoints.SingleAsync(e => e.EndpointId == seeded.EndpointId)).Deactivate();
            await db.SaveChangesAsync();
        }

        Assert.False(await ProcessNextAsync());
        Assert.Empty(_handler.Requests);
        Assert.Equal(DeliveryStatus.Queued, (await ReadDeliveryAsync()).Status);

        await using (var scope = _factory.Services.CreateAsyncScope())
        {
            var db = scope.ServiceProvider.GetRequiredService<EventFlowDbContext>();
            if (disabledResource == "project")
                (await db.Projects.SingleAsync(p => p.ProjectId == seeded.ProjectId)).Activate();
            else
                (await db.WebhookEndpoints.SingleAsync(e => e.EndpointId == seeded.EndpointId)).Activate();
            await db.SaveChangesAsync();
        }

        Assert.True(await ProcessNextAsync());
        Assert.Equal(DeliveryStatus.Delivered, (await ReadDeliveryAsync()).Status);
        Assert.Single(_handler.Requests);
    }

    private async Task<SeededDestination> SeedAsync(bool publish = true)
    {
        await using var scope = _factory.Services.CreateAsyncScope();
        var services = scope.ServiceProvider;
        var db = services.GetRequiredService<EventFlowDbContext>();
        var signingKeys = services.GetRequiredService<ISigningKeyService>();
        var project = Project.Create("Delivery integration", Guid.NewGuid()).Project;
        var secret = signingKeys.GenerateSigningKey();
        var endpoint = project.RegisterEndpoint("https://receiver.example/webhook", signingKeys.Encrypt(secret), "Receiver");
        endpoint.Subscribe("order.created");
        var apiKey = services.GetRequiredService<IApiKeyService>().Generate(isLive: true);
        project.GenerateApiKey(apiKey.HashedKey, apiKey.KeyPrefix, isLive: true);
        db.Projects.Add(project);
        await db.SaveChangesAsync();
        if (publish)
        {
            await services.GetRequiredService<IEventService>().CreateEventAsync(new EventInput(
                project.ProjectId, "order.created", new { orderId = "order-42" }, Guid.NewGuid().ToString()));
        }
        return new SeededDestination(project.ProjectId, endpoint.EndpointId, secret, apiKey.PlainTextKey);
    }

    private async Task<bool> ProcessNextAsync()
    {
        await using var scope = _factory.Services.CreateAsyncScope();
        return await scope.ServiceProvider.GetRequiredService<IDeliveryProcessor>().ProcessNextAsync();
    }

    private async Task SendJobAsync(Guid deliveryId)
    {
        await using var scope = _factory.Services.CreateAsyncScope();
        await scope.ServiceProvider.GetRequiredService<DeliveryJobs>().SendAsync(deliveryId, CancellationToken.None);
    }

    private async Task<Delivery> ReadDeliveryAsync()
    {
        await using var scope = _factory.Services.CreateAsyncScope();
        return await scope.ServiceProvider.GetRequiredService<EventFlowDbContext>().Deliveries
            .AsNoTracking().Include(d => d.Event).Include(d => d.Attempts).SingleAsync();
    }

    private sealed record SeededDestination(Guid ProjectId, Guid EndpointId, string Secret, string ApiKey);

    private sealed class RecordingJobClient : IBackgroundJobClient
    {
        public List<(Job Job, IState State)> Created { get; } = [];
        public bool FailEnqueue { get; set; }

        public string Create(Job job, IState state)
        {
            if (FailEnqueue)
                throw new InvalidOperationException("Job storage is unavailable.");

            Created.Add((job, state));
            return Created.Count.ToString(CultureInfo.InvariantCulture);
        }

        public bool ChangeState(string jobId, IState state, string expectedState) =>
            throw new NotSupportedException();
    }

    private sealed class ManualTimeProvider : TimeProvider
    {
        private DateTimeOffset _utcNow = new(2030, 1, 1, 12, 0, 0, TimeSpan.Zero);
        public override DateTimeOffset GetUtcNow() => _utcNow;
        public void Advance(TimeSpan duration) => _utcNow += duration;
        public void SetUtcNow(DateTimeOffset utcNow) => _utcNow = utcNow;
    }

    private sealed class RecordingHandler : HttpMessageHandler
    {
        private readonly Queue<Func<HttpResponseMessage>> _responses = new();
        public List<RecordedRequest> Requests { get; } = new();

        public void Enqueue(HttpStatusCode status, string body, TimeSpan? retryAfter = null)
        {
            _responses.Enqueue(() =>
            {
                var response = new HttpResponseMessage(status) { Content = new StringContent(body) };
                if (retryAfter is not null)
                    response.Headers.RetryAfter = new RetryConditionHeaderValue(retryAfter.Value);
                return response;
            });
        }

        protected override async Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken ct)
        {
            Requests.Add(new RecordedRequest(request.Method, request.RequestUri!.ToString(),
                await request.Content!.ReadAsStringAsync(ct), request.Content.Headers.ContentType?.MediaType,
                request.Headers.ToDictionary(h => h.Key, h => string.Join(",", h.Value), StringComparer.OrdinalIgnoreCase)));
            return _responses.Count > 0 ? _responses.Dequeue()() : new HttpResponseMessage(HttpStatusCode.NoContent);
        }
    }

    private sealed record RecordedRequest(HttpMethod Method, string Url, string Payload, string? ContentType,
        IReadOnlyDictionary<string, string> Headers);
}
